#!/usr/bin/env bash
# Убрать файл или каталог БЕЗ безвозвратного удаления.
#
# ПРАВИЛО (решение владельца, 2026-09-01):
#   убирая файлы — не удалять, а переносить в ../.recyclebin рядом с репозиториями;
#   исключение — файл, чьё содержимое ПОБАЙТОВО совпадает с уже сохранённой копией:
#   такой можно удалить, но запись об удалении обязана попасть в .recyclebin/.history.csv.
#
# ЗАЧЕМ. «Восстановимо из git» верно только пока цел коммит: ветки сводят, переименовывают
# и удаляют вместе с worktree. Под git-lfs указатель в истории остаётся, а объект уезжает
# в GC вместе с последним ref. Заигнорированные каталоги (.tmp/build/, data/generated/)
# не видит ни `git status`, ни проверки worktree_land.sh — оттуда файл исчезает молча.
# 2026-09-01 так чуть не пропал час ручной правки деки в .tmp/build/.
#
# ИСПОЛЬЗОВАНИЕ
#   scripts/recycle.sh <путь> [ещё путь…]         # перенести в корзину (по умолчанию)
#   scripts/recycle.sh --dup-of <копия> <путь>    # удалить как дубль, сверив sha256
#   scripts/recycle.sh --dry-run <путь>           # показать, что будет сделано
#
# Проверки перед необратимым шагом:
#   * файл открыт другим процессом (lsof) → отказ: удаление выдернет его из-под редактора;
#   * --dup-of: sha256 обязан совпасть, иначе отказ — «дубль» без сверки это не дубль;
#   * корзина и источник на разных томах → не mv, а копирование со сверкой sha256;
#   * КАЖДЫЙ шаг проверяется по коду возврата — mkdir корзины, запись в журнал, mv, cp, rm.
#     2026-09-02: под песочницей агента mv отказывал («Operation not permitted»: корзина лежит
#     ВНЕ репозитория), а скрипт печатал «перенесён» про пять файлов, оставшихся на месте.
#     В ветке с копированием было хуже: незамеченный отказ cp — и `rm -rf` уносил оригинал,
#     когда копии не существовало.
set -u

# Корзина живёт РЯДОМ с репозиториями, поэтому корень берём от ОСНОВНОГО чекаута, а не от
# расположения скрипта: в worktree (.claude/worktrees/<имя>/) отсчёт «на два вверх» дал бы
# .claude/.recyclebin. `--git-common-dir` в worktree указывает на .git основного чекаута.
_common=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null)
if [ -n "$_common" ]; then
  _repo_root=$(dirname "$_common")
else
  _repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." 2>/dev/null && pwd -P)
fi
BIN="${RECYCLEBIN:-$(dirname "$_repo_root")/.recyclebin}"
LOG="$BIN/.history.csv"
DRY=0
DUP_OF=""

die() { echo "recycle: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1; shift ;;
    --dup-of)  DUP_OF="${2:-}"; [ -n "$DUP_OF" ] || die "--dup-of требует путь к сохранённой копии"; shift 2 ;;
    --) shift; break ;;
    -*) die "неизвестный флаг: $1" ;;
    *) break ;;
  esac
done
[ $# -gt 0 ] || die "нечего убирать; см. заголовок файла"

# Корзина и журнал должны быть готовы ДО первого необратимого шага. Раньше их создание шло
# без проверки, и при недоступной корзине (сессия агента в песочнице: корзина лежит ВНЕ
# репозитория, запись туда запрещена) скрипт всё равно доходил до конца и рапортовал о
# переносе, которого не было.
mkdir -p "$BIN" || die "корзина недоступна: $BIN (в песочнице? корзина лежит вне репозитория)"
if [ ! -f "$LOG" ]; then
  printf 'ts_utc,action,path_from,repo,sha256,size_bytes,kept_at,reason,actor\n' > "$LOG" \
    || die "журнал недоступен для записи: $LOG"
fi
[ -w "$LOG" ] || die "журнал недоступен для записи: $LOG"

sha_of()  { shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1; }

# Слепок содержимого для сверки дублей: обычный файл — его sha256; каталог — sha256 от
# перечня «относительный путь + sha256» по всем файлам внутри, отсортированного.
# Пустая строка НЕ возвращается никогда: пустая с обеих сторон означала бы «совпало»
# и разрешала удаление без сверки — так каталог однажды и удалился бы вслепую.
digest_of() {
  local p="$1"
  if [ -f "$p" ] && [ ! -L "$p" ]; then
    sha_of "$p"
  elif [ -d "$p" ] && [ ! -L "$p" ]; then
    # непростые типы внутри (симлинк, сокет, fifo) делают сверку неполной — отказ
    if find "$p" \! -type f \! -type d -print -quit 2>/dev/null | grep -q .; then
      echo "MIXED"
      return 0
    fi
    ( cd "$p" 2>/dev/null || exit 1
      find . -type f -print0 2>/dev/null | LC_ALL=C sort -z | while IFS= read -r -d '' f; do
        printf '%s  %s\n' "$(shasum -a 256 "$f" 2>/dev/null | cut -d' ' -f1)" "$f"
      done ) | shasum -a 256 | cut -d' ' -f1
  else
    echo ""   # симлинк, устройство, отсутствие — сверка невозможна
  fi
}
size_of() { stat -f %z "$1" 2>/dev/null || stat -c %s "$1" 2>/dev/null; }
dev_of()  { stat -f %d "$1" 2>/dev/null || stat -c %d "$1" 2>/dev/null; }

# Запись в журнал — часть правила, а не отчётность: «удалять можно, если запись ушла». Поэтому
# неудачная запись останавливает скрипт, а не проходит молча. Вызывать ДО необратимого шага.
log_row() { # action path repo sha size kept reason
  printf '%s,%s,%s,%s,%s,%s,"%s","%s",%s\n' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$1" "$2" "$3" "$4" "$5" "$6" "$7" "${ACTOR:-$(whoami)}" >> "$LOG" \
    || die "не удалось записать в журнал $LOG — ничего не тронуто"
}

for target in "$@"; do
  [ -e "$target" ] || die "нет такого пути: $target"

  # 1. кто-то держит открытым — не трогаем
  if command -v lsof >/dev/null && lsof -- "$target" >/dev/null 2>&1; then
    holder=$(lsof -t -- "$target" 2>/dev/null | head -1)
    die "$target открыт процессом $holder — сначала закройте, иначе правка уйдёт в никуда"
  fi

  repo=$(basename "$(git -C "$(dirname "$target")" rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null)
  repo="${repo:--}"
  sha=$(sha_of "$target")
  size=$(size_of "$target")

  if [ -n "$DUP_OF" ]; then
    # 2. дубль удаляем ТОЛЬКО после сверки содержимого
    [ -e "$DUP_OF" ] || die "копия не найдена: $DUP_OF"
    # …и только если «копия» — действительно ДРУГОЙ файл. Иначе сверка вырождается в
    # сравнение файла с самим собой, всегда проходит, и скрипт удаляет единственный
    # экземпляр, записав в журнал, что копия осталась «там же». Ловится по inode, а не
    # по строке пути: ./x, x и симлинк на x — один и тот же файл.
    if [ "$(cd "$(dirname "$target")" && pwd -P)/$(basename "$target")" = \
         "$(cd "$(dirname "$DUP_OF")" && pwd -P)/$(basename "$DUP_OF")" ] || \
       [ "$target" -ef "$DUP_OF" ]; then
      die "--dup-of указывает на сам удаляемый файл ($target) — это не сверка, а её видимость; укажите ДРУГУЮ копию"
    fi
    # Сверять можно только однотипное: файл с файлом, каталог с каталогом.
    if { [ -d "$target" ] && [ ! -d "$DUP_OF" ]; } || { [ ! -d "$target" ] && [ -d "$DUP_OF" ]; }; then
      die "разные типы: $target и $DUP_OF (файл против каталога) — сверка невозможна, переносите"
    fi
    mine=$(digest_of "$target"); other=$(digest_of "$DUP_OF")
    # ПУСТОЙ слепок раньше означал молчаливое «совпало»: shasum на каталоге ничего не
    # печатает, обе стороны выходили пустыми, и каталог удалялся без единой сверки.
    [ -n "$mine" ]  || die "не удалось посчитать содержимое $target (симлинк? устройство?) — сверка невозможна, переносите"
    [ -n "$other" ] || die "не удалось посчитать содержимое $DUP_OF — сверка невозможна, переносите"
    [ "$mine" != "MIXED" ] && [ "$other" != "MIXED" ] || die "внутри есть не только обычные файлы (симлинк/сокет/fifo) — сверка была бы неполной, переносите"
    [ "$mine" = "$other" ] || die "не дубль: $target ($mine) ≠ $DUP_OF ($other) — переносите, а не удаляйте"
    if [ "$DRY" = 1 ]; then echo "[dry] удалить как дубль: $target (копия $DUP_OF)"; continue; fi
    log_row deleted-duplicate "$target" "$repo" "$mine" "$size" "$DUP_OF" "$([ -d "$target" ] && echo 'точный дубль каталога: совпал слепок «путь+sha256» по всем файлам' || echo 'точный дубль по sha256')"
    rm -rf -- "$target" || die "запись в журнал ушла, но удалить не вышло: $target"
    echo "удалён как дубль: $target → копия остаётся в $DUP_OF (запись в $LOG)"
    continue
  fi

  # 3. обычный путь — перенос в корзину
  dest="$BIN/$(date -u +%Y%m%d)-$(basename "$target")"
  n=1
  while [ -e "$dest" ]; do dest="$BIN/$(date -u +%Y%m%d)-$n-$(basename "$target")"; n=$((n+1)); done
  if [ "$DRY" = 1 ]; then echo "[dry] перенести: $target → $dest"; continue; fi

  if [ "$(dev_of "$target")" = "$(dev_of "$BIN")" ]; then
    # Один том: переименование, атомарно. Код возврата обязателен к проверке — mv может
    # отказать (права, песочница, том только для чтения), и без проверки скрипт печатал
    # «перенесён» про файл, оставшийся на месте.
    mv -- "$target" "$dest" || die "не удалось перенести $target → $dest (оригинал на месте)"
  else
    # Разные тома: копия → сверка → удаление. Отказ cp здесь ОСОБЕННО опасен: без проверки
    # дальше шёл `rm -rf` оригинала, а копии не существовало — файл исчезал совсем.
    cp -R -p -- "$target" "$dest" || die "не удалось скопировать $target → $dest (оригинал на месте)"
    [ -e "$dest" ] || die "копия не появилась: $dest — оригинал НЕ тронут"
    if [ -f "$dest" ] && [ "$(sha_of "$dest")" != "$sha" ]; then
      die "копия не сошлась по sha256, оригинал НЕ тронут: $target"
    fi
    rm -rf -- "$target" || die "копия сделана ($dest), но оригинал не удалён: $target"
  fi
  log_row moved "$target" "$repo" "$sha" "$size" "$dest" "убран из репозитория, не удалён"
  echo "перенесён: $target → $dest (запись в $LOG)"
done
